#!/usr/bin/env python3
"""generate_tutorials.py

Scans assets/tutorials and assets/dev/tutorials for tutorial markdown files,
extracts tutorial titles, and generates lib/tutorials.g.dart.
"""

import glob
import os
import re
import sys


def extract_title(file_path):
    """Extracts title from the first '# Title' header or filename fallback."""
    try:
        with open(file_path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line.startswith("# "):
                    return line[2:].strip()
    except Exception as e:
        print(f"Warning: Failed to read {file_path}: {e}", file=sys.stderr)

    # Fallback to humanized filename
    basename = os.path.basename(file_path)
    name_without_ext, _ = os.path.splitext(basename)
    return name_without_ext.replace("_", " ").replace("-", " ").title()


def escape_dart_string(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")


def scan_tutorials(directory):
    """Returns sorted list of (file_path, title, {locale: localized_title}) tuples."""
    if not os.path.isdir(directory):
        return []
    md_files = glob.glob(os.path.join(directory, "*.md"))
    base_files = {}
    localized_files = {}

    for f in md_files:
        norm_path = os.path.normpath(f)
        basename = os.path.basename(norm_path)
        name_no_ext, _ = os.path.splitext(basename)
        parts = name_no_ext.split("_")
        matched = False

        # Check for 2-part locale suffix (e.g. en_gb, zh_cn)
        if len(parts) >= 3 and len(parts[-2]) == 2 and len(parts[-1]) in (2, 4):
            candidate_base = "_".join(parts[:-2]) + ".md"
            candidate_base_path = os.path.join(os.path.dirname(norm_path), candidate_base)
            if os.path.exists(candidate_base_path):
                loc_key = f"{parts[-2]}_{parts[-1]}".lower()
                localized_files[(candidate_base_path, loc_key)] = norm_path
                matched = True

        # Check for 1-part locale suffix (e.g. de, es, fr, ja, lt, pt, zh)
        if not matched and len(parts) >= 2 and len(parts[-1]) in (2, 3):
            candidate_base = "_".join(parts[:-1]) + ".md"
            candidate_base_path = os.path.join(os.path.dirname(norm_path), candidate_base)
            if os.path.exists(candidate_base_path):
                loc_key = parts[-1].lower()
                localized_files[(candidate_base_path, loc_key)] = norm_path
                matched = True

        if not matched:
            base_files[norm_path] = extract_title(norm_path)

    results = []
    for base_path in sorted(base_files.keys()):
        base_title = base_files[base_path]
        loc_map = {}
        for (bp, loc), loc_path in localized_files.items():
            if bp == base_path:
                loc_map[loc] = extract_title(loc_path)
        results.append((base_path, base_title, loc_map))
    return results


def main():
    root_dir = os.path.abspath(os.path.dirname(__file__))
    tutorials_dir = os.path.join(root_dir, "assets", "tutorials")
    dev_tutorials_dir = os.path.join(root_dir, "assets", "dev", "tutorials")
    output_file = os.path.join(root_dir, "lib", "tutorials.g.dart")

    built_in = scan_tutorials(tutorials_dir)
    dev_built_in = scan_tutorials(dev_tutorials_dir)

    lines = []
    lines.append("// GENERATED CODE - DO NOT MODIFY BY HAND")
    lines.append("// Generated by generate_tutorials.py")
    lines.append("")
    lines.append("import 'file_holder.dart';")
    lines.append("import 'settings.dart';")
    lines.append("")
    lines.append("final List<AssetHolder> kBuiltInTutorials = [")
    for path, title, loc_map in built_in:
        rel_path = os.path.relpath(path, root_dir)
        lines.append("  AssetHolder(")
        lines.append(f'    "{escape_dart_string(rel_path)}",')
        lines.append(f'    title: "{escape_dart_string(title)}",')
        if loc_map:
            lines.append("    localizedTitles: const {")
            for loc, loc_title in sorted(loc_map.items()):
                lines.append(
                    f'      "{loc}": "{escape_dart_string(loc_title)}",'
                )
            lines.append("    },")
        lines.append("  ),")
    lines.append("];")
    lines.append("")
    lines.append("final List<AssetHolder> kDevTutorials = [")
    for path, title, loc_map in dev_built_in:
        rel_path = os.path.relpath(path, root_dir)
        lines.append("  AssetHolder(")
        lines.append(f'    "{escape_dart_string(rel_path)}",')
        lines.append(f'    title: "{escape_dart_string(title)}",')
        if loc_map:
            lines.append("    localizedTitles: const {")
            for loc, loc_title in sorted(loc_map.items()):
                lines.append(
                    f'      "{loc}": "{escape_dart_string(loc_title)}",'
                )
            lines.append("    },")
        lines.append("  ),")
    lines.append("];")
    lines.append("")
    lines.append("/// Returns the list of available built-in tutorials.")
    lines.append(
        "/// Dev tutorials from assets/dev/tutorials/ are included whenever"
    )
    lines.append("/// [Settings.kDebugEnabled] is true (or when [includeDev] is explicitly true).")
    lines.append("List<AssetHolder> getBuiltInTutorials({bool? includeDev}) {")
    lines.append("  final showDev = includeDev ?? Settings.kDebugEnabled;")
    lines.append("  if (showDev) {")
    lines.append("    return [...kBuiltInTutorials, ...kDevTutorials];")
    lines.append("  }")
    lines.append("  return kBuiltInTutorials;")
    lines.append("}")
    lines.append("")

    content = "\n".join(lines)
    with open(output_file, "w", encoding="utf-8") as f:
        f.write(content)

    import subprocess
    try:
        subprocess.run(["dart", "format", output_file], check=False, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    except Exception:
        pass

    print(
        f"Generated {output_file} with {len(built_in)} built-in tutorials and {len(dev_built_in)} dev tutorials."
    )


if __name__ == "__main__":
    main()
