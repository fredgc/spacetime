#!/usr/bin/env python3
"""generate_tutorials.py

Scans assets/tutorials and assets/dev/tutorials for tutorial markdown files,
extracts tutorial titles, and generates lib/tutorials.g.dart.
"""

import glob
import os
import re
import sys


def extract_title(file_path):
    """Extracts title from the first '# Title' header or filename fallback."""
    try:
        with open(file_path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line.startswith("# "):
                    return line[2:].strip()
    except Exception as e:
        print(f"Warning: Failed to read {file_path}: {e}", file=sys.stderr)

    # Fallback to humanized filename
    basename = os.path.basename(file_path)
    name_without_ext, _ = os.path.splitext(basename)
    return name_without_ext.replace("_", " ").replace("-", " ").title()


def escape_dart_string(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")


def scan_tutorials(directory):
    """Returns sorted list of (file_path, title) tuples."""
    if not os.path.isdir(directory):
        return []
    md_files = sorted(glob.glob(os.path.join(directory, "*.md")))
    results = []
    for path in md_files:
        norm_path = os.path.normpath(path)
        title = extract_title(norm_path)
        results.append((norm_path, title))
    return results


def main():
    root_dir = os.path.abspath(os.path.dirname(__file__))
    tutorials_dir = os.path.join(root_dir, "assets", "tutorials")
    dev_tutorials_dir = os.path.join(root_dir, "assets", "dev", "tutorials")
    output_file = os.path.join(root_dir, "lib", "tutorials.g.dart")

    built_in = scan_tutorials(tutorials_dir)
    dev_built_in = scan_tutorials(dev_tutorials_dir)

    lines = []
    lines.append("// GENERATED CODE - DO NOT MODIFY BY HAND")
    lines.append("// Generated by generate_tutorials.py")
    lines.append("")
    lines.append("import 'file_holder.dart';")
    lines.append("import 'settings.dart';")
    lines.append("")
    lines.append("final List<AssetHolder> kBuiltInTutorials = [")
    for path, title in built_in:
        rel_path = os.path.relpath(path, root_dir)
        lines.append("  AssetHolder(")
        lines.append(f'    "{escape_dart_string(rel_path)}",')
        lines.append(f'    title: "{escape_dart_string(title)}",')
        lines.append("  ),")
    lines.append("];")
    lines.append("")
    lines.append("final List<AssetHolder> kDevTutorials = [")
    for path, title in dev_built_in:
        rel_path = os.path.relpath(path, root_dir)
        lines.append("  AssetHolder(")
        lines.append(f'    "{escape_dart_string(rel_path)}",')
        lines.append(f'    title: "{escape_dart_string(title)}",')
        lines.append("  ),")
    lines.append("];")
    lines.append("")
    lines.append("/// Returns the list of available built-in tutorials.")
    lines.append(
        "/// Dev tutorials from assets/dev/tutorials/ are included whenever"
    )
    lines.append("/// [Settings.kDebugEnabled] is true (or when [includeDev] is explicitly true).")
    lines.append("List<AssetHolder> getBuiltInTutorials({bool? includeDev}) {")
    lines.append("  final showDev = includeDev ?? Settings.kDebugEnabled;")
    lines.append("  if (showDev) {")
    lines.append("    return [...kBuiltInTutorials, ...kDevTutorials];")
    lines.append("  }")
    lines.append("  return kBuiltInTutorials;")
    lines.append("}")
    lines.append("")

    content = "\n".join(lines)
    with open(output_file, "w", encoding="utf-8") as f:
        f.write(content)

    import subprocess
    try:
        subprocess.run(["dart", "format", output_file], check=False, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    except Exception:
        pass

    print(
        f"Generated {output_file} with {len(built_in)} built-in tutorials and {len(dev_built_in)} dev tutorials."
    )


if __name__ == "__main__":
    main()
